"""Run the retrieval evaluation.

    python evals/run.py                 # offline lexical + metadata retrieval
    python evals/run.py --vector        # include the ChromaDB vector layer
    python evals/run.py --out evals/results

The demo library is generated into a throwaway directory and deleted
afterwards. This script refuses to run against any upload root other than the
one it created, so it can never purge a real library.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def _build_assets(work: Path) -> list:
    """Generate the demo corpus inside ``work`` and load it as ProjectAssets."""
    sys.path.insert(0, str(ROOT / "scripts"))
    import seed_demo  # noqa: PLC0415 - must load after SESSIONIQ_UPLOAD_ROOT is set

    from sessioniq.models import ProjectAsset  # noqa: PLC0415
    from sessioniq.project_workspace import UPLOAD_ROOT  # noqa: PLC0415

    if not str(UPLOAD_ROOT.resolve()).startswith(str(work.resolve())):
        raise SystemExit(
            f"refusing to run: upload root {UPLOAD_ROOT} is outside the temporary "
            f"directory {work}"
        )

    seed_demo.purge()
    seed_demo.build()
    index = json.loads((work / "library-index.json").read_text(encoding="utf-8"))
    return [ProjectAsset.model_validate(entry) for entry in index["assets"]]


def _markdown(report, generated_at: str) -> str:
    lines: list[str] = []
    add = lines.append

    add("# Retrieval evaluation")
    add("")
    add(f"Generated {generated_at} by `python evals/run.py`.")
    add("")
    add(f"- Corpus: **{report.corpus_size} assets** across **{report.projects} projects**, "
        "generated by `scripts/seed_demo.py`")
    add(f"- Queries: **{report.baseline.cases}** labeled questions in `evals/golden_set.py`")
    add(f"- Vector layer: **{'enabled' if report.vector_enabled else 'disabled'}**")
    add(f"- Ranking fidelity: re-ranked order matched `search()` on "
        f"**{report.faithfulness_checked}** queries "
        f"({len(report.faithfulness_mismatches)} mismatches)")
    add("")

    summary = report.baseline
    add("## Headline")
    add("")
    add("| metric | @1 | @3 | @5 |")
    add("| --- | --- | --- | --- |")
    add(f"| hit rate | {summary.hit[1]:.3f} | {summary.hit[3]:.3f} | {summary.hit[5]:.3f} |")
    add(f"| recall | {summary.recall[1]:.3f} | {summary.recall[3]:.3f} | {summary.recall[5]:.3f} |")
    add(f"| precision | {summary.precision[1]:.3f} | {summary.precision[3]:.3f} | "
        f"{summary.precision[5]:.3f} |")
    add(f"| MRR | {summary.mrr:.3f} | | |")
    add("")

    lat = report.latency_ms
    add("## Latency per query")
    add("")
    add(f"Measured over {lat['calls']} calls (p50 **{lat['p50']} ms**, "
        f"p95 **{lat['p95']} ms**, max {lat['max']} ms, mean {lat['mean']} ms).")
    add("")

    add("## By question type")
    add("")
    add("| category | n | hit@1 | hit@3 | hit@5 | MRR |")
    add("| --- | --- | --- | --- | --- | --- |")
    for name, cat in report.by_category.items():
        add(f"| {name} | {cat.cases} | {cat.hit[1]:.3f} | {cat.hit[3]:.3f} | "
            f"{cat.hit[5]:.3f} | {cat.mrr:.3f} |")
    add("")

    tool_passed = sum(1 for r in report.tool_results if r.passed)
    add("## Computable questions (tool layer)")
    add("")
    add("Superlative questions ask for a comparison, not for a similar file, so every audio "
        "file matches the query words about equally well and ranking cannot pick a winner. "
        "`compute_stat` compares the real numbers instead.")
    add("")
    add(f"**{tool_passed}/{len(report.tool_results)}** returned the correct asset.")
    add("")
    add("| question | field | op | expected | tool returned | |")
    add("| --- | --- | --- | --- | --- | --- |")
    for result in report.tool_results:
        mark = "ok" if result.passed else "**wrong**"
        expected = (
            result.expected[0]
            if len(result.expected) == 1
            else f"one of {len(result.expected)} tied"
        )
        add(f"| {result.question} | {result.field} | {result.op} | {expected} | "
            f"{result.actual or '(nothing)'} | {mark} |")
    add("")

    add("## Blend weight ablation")
    add("")
    add("Component scores are held fixed and only the blend weights change, so each row "
        "isolates what the weighting is worth.")
    add("")
    add("| configuration | hit@1 | hit@3 | hit@5 | recall@5 | precision@5 | MRR |")
    add("| --- | --- | --- | --- | --- | --- | --- |")
    for row in report.ablation:
        s = row.summary
        add(f"| {row.name} | {s.hit[1]:.3f} | {s.hit[3]:.3f} | {s.hit[5]:.3f} | "
            f"{s.recall[5]:.3f} | {s.precision[5]:.3f} | {s.mrr:.3f} |")
    add("")

    add("## Cases not ranked first")
    add("")
    add(f"{len(report.weak_cases)} of {report.baseline.cases} questions did not put an expected "
        f"file at rank 1; {report.unretrieved} of those retrieved no expected file at all.")
    add("")
    if report.weak_cases:
        add("| question | category | first relevant rank | top result |")
        add("| --- | --- | --- | --- |")
        for case in report.weak_cases:
            rank = case["first_relevant_rank"] or "not retrieved"
            top = case["retrieved"][0] if case["retrieved"] else "(nothing)"
            add(f"| {case['question']} | {case['category']} | {rank} | {top} |")
        add("")
        add("The superlative questions dominate this list by design — they are the ones the "
            "tool layer answers exactly, above.")
    add("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=str(ROOT / "evals" / "results"),
                        help="directory for the JSON and Markdown reports")
    parser.add_argument("--vector", action="store_true",
                        help="enable the ChromaDB vector layer (downloads a model)")
    parser.add_argument("--keep", action="store_true",
                        help="keep the generated corpus for inspection")
    args = parser.parse_args()

    work = Path(tempfile.mkdtemp(prefix="sessioniq-eval-"))
    os.environ["SESSIONIQ_UPLOAD_ROOT"] = str(work / "uploads")
    if not args.vector:
        os.environ["SESSIONIQ_DISABLE_VECTOR"] = "1"

    try:
        from evals.harness import run_eval  # noqa: PLC0415
        from sessioniq.retrieval import HybridRetriever, InMemoryRetriever  # noqa: PLC0415

        print(f"building demo corpus in {work} ...")
        assets = _build_assets(work)

        retriever = (
            HybridRetriever(persist_directory=work / "chroma")
            if args.vector
            else InMemoryRetriever()
        )
        retriever.add_assets(assets)
        vector_on = bool(getattr(retriever, "vector_enabled", False))
        print(f"vector layer: {'enabled' if vector_on else 'disabled'}")

        report = run_eval(retriever, vector_enabled=vector_on)

        if report.faithfulness_mismatches:
            print("\nRANKING FIDELITY FAILED — the harness does not reproduce search():")
            for mismatch in report.faithfulness_mismatches:
                print(f"  {mismatch}")
            return 1

        from datetime import UTC, datetime  # noqa: PLC0415

        generated = datetime.now(UTC).strftime("%Y-%m-%d")
        out_dir = Path(args.out)
        out_dir.mkdir(parents=True, exist_ok=True)
        tool_passed = sum(1 for r in report.tool_results if r.passed)

        payload = {
            "generated": generated,
            "corpus_size": report.corpus_size,
            "projects": report.projects,
            "vector_enabled": report.vector_enabled,
            "questions": report.baseline.cases,
            "baseline": report.baseline.as_dict(),
            "by_category": {k: v.as_dict() for k, v in report.by_category.items()},
            "ablation": [{"name": r.name, **r.summary.as_dict()} for r in report.ablation],
            "latency_ms": report.latency_ms,
            "tool_accuracy": {
                "passed": tool_passed,
                "total": len(report.tool_results),
                "cases": [
                    {
                        "question": r.question,
                        "field": r.field,
                        "op": r.op,
                        "expected": list(r.expected),
                        "actual": r.actual,
                        "passed": r.passed,
                    }
                    for r in report.tool_results
                ],
            },
            "weak_cases": report.weak_cases,
            "unretrieved": report.unretrieved,
            "ranking_fidelity": {
                "checked": report.faithfulness_checked,
                "mismatches": report.faithfulness_mismatches,
            },
        }
        stem = "retrieval-report-vector" if report.vector_enabled else "retrieval-report"
        (out_dir / f"{stem}.json").write_text(
            json.dumps(payload, indent=2), encoding="utf-8"
        )
        (out_dir / f"{stem}.md").write_text(
            _markdown(report, generated), encoding="utf-8"
        )

        print(f"\nwrote {out_dir / f'{stem}.md'}")
        print(f"wrote {out_dir / f'{stem}.json'}")
        print(f"\nhit@1 {report.baseline.hit[1]:.3f}  hit@3 {report.baseline.hit[3]:.3f}  "
              f"hit@5 {report.baseline.hit[5]:.3f}  MRR {report.baseline.mrr:.3f}  "
              f"p95 {report.latency_ms['p95']} ms")
        print(f"tool accuracy {tool_passed}/{len(report.tool_results)}")
        return 0
    finally:
        if args.keep:
            print(f"corpus kept at {work}")
        else:
            shutil.rmtree(work, ignore_errors=True)


if __name__ == "__main__":
    raise SystemExit(main())
